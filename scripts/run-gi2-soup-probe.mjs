// GI2 STAGE 2.2 — drives scripts/gi2-soup.html and prints the stall receipt.
//
// PLAN §5 Stage 2.2's gate is "main-thread stall at scene open < 50 ms; Bistro
// grid built in the worker ≤ 2 s". Only a browser can answer it: the stall is a
// main thread that node does not have, and the worker URL is resolved by Vite,
// which is where this engine's FIRST `new Worker` can break in a way no unit
// test sees (dev serves an ES module; a build emits a hashed chunk; Tauri loads
// that chunk over a custom protocol).
//
// Run: node scripts/run-gi2-soup-probe.mjs [url]
//      (the gi19 worktree's private-cache vite server is :5202, never :5201)
import puppeteer from "puppeteer-core";

const url = process.argv[2] ?? "http://127.0.0.1:5202/scripts/gi2-soup.html";

const browser = await puppeteer.launch({
  executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe",
  headless: process.env.HEADED ? false : "new",
  args: ["--no-sandbox", "--disable-dev-shm-usage"],
});

const page = await browser.newPage();
const logs = [];
page.on("console", (m) => logs.push(m.text()));
page.on("pageerror", (e) => logs.push(`PAGEERROR ${e.stack ?? e.message}`));
// A worker that fails to fetch shows up here and nowhere else.
page.on("requestfailed", (r) => logs.push(`REQUESTFAILED ${r.url()} ${r.failure()?.errorText ?? ""}`));
page.on("response", (r) => { if (r.status() >= 400) logs.push(`HTTP ${r.status()} ${r.url()}`); });
let workerUrls = [];
page.on("workercreated", (w) => workerUrls.push(w.url()));

let failed = 0;
try {
  await page.goto(url, { waitUntil: "domcontentloaded", timeout: 60000 });
  await page.waitForFunction("globalThis.__GI2_SOUP_RESULT__ !== undefined", { timeout: 300000 });
  const r = await page.evaluate("globalThis.__GI2_SOUP_RESULT__");
  if (r?.text) console.log(r.text.split("\n").map((l) => `  ${l}`).join("\n"));
  console.log("");
  // The page can only observe that SOMETHING built the soup; the CDP worker
  // event is the independent witness that a real Worker thread existed.
  console.log(`workers spawned: ${workerUrls.length ? workerUrls.join(", ") : "NONE — the build ran on the main thread"}`);
  if (!workerUrls.some((u) => /triangleSoup\.worker/.test(u))) {
    failed++;
    console.error("  FAIL no triangleSoup worker was created");
  }
  if (r?.pass) {
    console.log("");
    console.log("STAGE 2.2 GATE");
    console.log("gate                                 measured        limit    verdict");
    const row = (name, value, limit, ok) =>
      console.log(`${name.padEnd(36)} ${value.padStart(13)}   ${limit.padStart(6)}    ${ok ? "PASS" : "FAIL"}`);
    row("main-thread stall at scene open", `${r.tickerMaxGapMs.toFixed(1)} ms`, "< 50", r.tickerMaxGapMs < 50);
    row("  (of which: copy + postMessage)", `${r.stallMs.toFixed(1)} ms`, "—", true);
    row("  (longtask observer)", `${r.longestTaskMs.toFixed(1)} ms`, "< 50", r.longestTaskMs < 50);
    row("Bistro-scale grid built in worker", `${r.buildMs.toFixed(0)} ms`, "≤ 2000", r.buildMs <= 2000);
    row("  (wall, post → result)", `${r.wallMs.toFixed(0)} ms`, "—", true);
    row("  (worker spawn)", `${r.spawnMs.toFixed(1)} ms`, "—", true);
    console.log(`\nsoup: ${r.triCount.toLocaleString()} tris, ${(r.bytes / 1048576).toFixed(1)} MB, grid ${r.dim.join("×")}, ${r.cellEntries.toLocaleString()} cell entries`);
    console.log(`input: ${r.inputMB.toFixed(1)} MB of geometry, generated by the harness in ${r.genMs.toFixed(0)} ms`);
  } else {
    failed++;
    console.error(`  FAIL ${r?.error ?? "no result"}`);
    for (const c of r?.checks ?? []) if (!c.ok) console.error(`    failed check: ${c.name}`);
    const noise = logs.filter((l) => /error|Error|fail|FAILED|HTTP/i.test(l)).slice(-8);
    if (noise.length) console.error(noise.map((l) => `    ${l}`).join("\n"));
  }
} catch (err) {
  failed++;
  console.error(`  FAIL ${err.message}`);
  console.error(logs.slice(-15).map((l) => `    ${l}`).join("\n"));
}
await page.close();
await browser.close();
process.exit(failed ? 1 : 0);
