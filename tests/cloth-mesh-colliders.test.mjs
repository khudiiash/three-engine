function fixture(props = {}, options = {}) {
  const engine = { entities: new Map(), playing: false };
  const entity = new Entity(engine,{id:'surface',name:'Arch'});
  engine.entities.set(entity.id,entity);
  const collider = new ColliderComponent({shape:'concave',...props});
  entity.components.set('collider',collider); collider.entity=entity;
  const field = new ClothMeshColliderField(engine,options); field.addUser();
  const add = (geometry,position=[0,0,0]) => {
    const mesh = new THREE.Mesh(geometry); mesh.position.fromArray(position);
    mesh.userData.entityId=entity.id; entity.object3D.add(mesh); return mesh;
  };
  return {engine,entity,collider,field,add};
}
function intersects(field,origin,direction,skip=-1) {
  const ray = new THREE.Ray(new THREE.Vector3(...origin),new THREE.Vector3(...direction));
  const data=field.data, point=new THREE.Vector3();
  let index=0, visits=0;
  while(index<field.countUniform.value) {
    assert.ok(visits++<field.countUniform.value+1,'stackless traversal terminates');
    const base=index*20;
    const box=new THREE.Box3(new THREE.Vector3().fromArray(data,base),new THREE.Vector3().fromArray(data,base+4));
    if(!ray.intersectsBox(box)){index=data[base+3];continue;}
    if(data[base+7]===1){
      if(data[base+19]!==skip && ray.intersectTriangle(new THREE.Vector3().fromArray(data,base+8),new THREE.Vector3().fromArray(data,base+12),new THREE.Vector3().fromArray(data,base+16),false,point))return point.clone();
      index=data[base+3];
    }else index++;
  }
  return null;
}

test('concave arch preserves opening and stackless BVH hits actual side surfaces',()=>{
  const {field,add}=fixture({autoGenerated:true});
  add(new THREE.BoxGeometry(1,4,1),[-2,0,0]);
  add(new THREE.BoxGeometry(1,4,1),[2,0,0]);
  add(new THREE.BoxGeometry(5,1,1),[0,2,0]);
  field.refresh();
  assert.equal(field.triangleCount,36);
  assert.equal(field.countUniform.value,71);
  assert.equal(intersects(field,[0,0,5],[0,0,-1]),null,'open doorway remains empty');
  assert.ok(intersects(field,[2,0,5],[0,0,-1]));
  assert.ok(intersects(field,[0,2,5],[0,0,-1]));
  assert.equal(intersects(field,[2,0,5],[0,0,-1],field.entityIndices.get('surface')),null,'per-simulation owner skip');
});

test('cooked simplified concave takes precedence; mesh uses unsimplified cooked source',()=>{
  const {engine,entity,collider,field,add}=fixture();
  add(new THREE.BoxGeometry(100,100,100));
  const triangle={vertices:new Float32Array([-1,-1,0,1,-1,0,0,1,0]),indices:new Uint32Array([0,1,2])};
  const cooked={vertices:new Float32Array([-1,-1,2,1,-1,2,0,1,2]),indices:new Uint32Array([0,1,2]),concave:triangle};
  engine.physics={getCookedColliderGeometry:()=>cooked};
  field.refresh(); assert.equal(field.triangleCount,1);
  assert.equal(intersects(field,[0,0,5],[0,0,-1]).z,0);
  collider.props.shape='mesh'; field.refresh();
  assert.equal(intersects(field,[0,0,5],[0,0,-1]).z,2);
  assert.equal(field.entityIndices.get(entity.id),0);
});

