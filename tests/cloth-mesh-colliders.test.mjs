test('global shell ids remain separate across opposite-winding islands and collider owners',()=>{
  const {engine,entity,field,add}=fixture();
  add(new THREE.BoxGeometry(2,2,2),[-3,0,0]);
  const reverse=new THREE.BoxGeometry(2,2,2);const index=reverse.index.array;
  for(let i=0;i<index.length;i+=3)[index[i],index[i+1]]=[index[i+1],index[i]];
  add(reverse,[3,0,0]);
  const other=new Entity(engine,{id:'other'});engine.entities.set(other.id,other);
  other.components.set('collider',new ColliderComponent({shape:'concave'}));
  other.object3D.add(new THREE.Mesh(new THREE.BoxGeometry(1,1,1)));
  field.refresh();assert.equal(field.closedShellCountUniform.value,3);
  const shells=new Map();
  for(let i=0;i<field.countUniform.value;i++) {
    const base=i*20;
    if(field.data[base+7]) {
      const id=field.data[base+15], owner=field.data[base+19];
      if(!shells.has(id))shells.set(id,{owners:new Set(),signs:new Set(),count:0});
      const shell=shells.get(id);shell.owners.add(owner);shell.signs.add(field.data[base+11]);shell.count++;
    } else {
      const descendants=[];
      for(let j=i+1;j<field.data[base+3];j++)if(field.data[j*20+7])descendants.push(field.data[j*20+15]);
      assert.equal(field.data[base+15],Math.min(...descendants));
      assert.equal(field.data[base+19],Math.max(...descendants));
    }
  }
  assert.equal(shells.size,3);
  for(const shell of shells.values()){assert.equal(shell.owners.size,1);assert.equal(shell.signs.size,1);assert.equal(shell.count,12);}
  assert.deepEqual([...shells.values()].map(s=>[...s.signs][0]).sort(),[-1,1,1]);
});
